SELECT
-- PMK France Publications — Koha 25.11 UNIMARC, lecture seule, sans paramètre.
-- Conserver cet ordre et les alias. Les colonnes facultatives non disponibles sont NULL.

    s.subscriptionid AS `subscription_id`,
    s.biblionumber AS `biblio_id`,
    b.title AS `title`,
    bi.issn AS `issn`,
    s.branchcode AS `library_id`,
    s.startdate AS `start_date`,
    s.enddate AS `end_date`,
    s.`closed` AS `closed`,
    s.aqbooksellerid AS `vendor_id`,
    v.name AS `vendor_name`,
    NULL AS `subscriber_number`,
    s.`notes` AS `notes`,
    s.internalnotes AS `internal_notes`,
    s.`callnumber` AS `callnumber`,
    s.graceperiod AS `grace_period`,
    s.periodicity AS `frequency_id`,
    s.numberpattern AS `number_pattern_id`,
    NULL AS `publisher`,
    s.`librarian` AS `librarian`,
    s.`cost` AS `cost`,
    s.`aqbudgetid` AS `aqbudgetid`,
    s.`weeklength` AS `weeklength`,
    s.`monthlength` AS `monthlength`,
    s.`numberlength` AS `numberlength`,
    s.`countissuesperunit` AS `countissuesperunit`,
    s.`status` AS `status`,
    s.`lastvalue1` AS `lastvalue1`,
    s.`innerloop1` AS `innerloop1`,
    s.`lastvalue2` AS `lastvalue2`,
    s.`innerloop2` AS `innerloop2`,
    s.`lastvalue3` AS `lastvalue3`,
    s.`innerloop3` AS `innerloop3`,
    s.`firstacquidate` AS `firstacquidate`,
    s.`manualhistory` AS `manualhistory`,
    s.`irregularity` AS `irregularity`,
    s.`skip_serialseq` AS `skip_serialseq`,
    s.`letter` AS `letter`,
    s.`locale` AS `locale`,
    s.`distributedto` AS `distributedto`,
    s.`location` AS `location`,
    s.`lastbranch` AS `lastbranch`,
    s.`serialsadditems` AS `serialsadditems`,
    s.`staffdisplaycount` AS `staffdisplaycount`,
    s.`opacdisplaycount` AS `opacdisplaycount`,
    s.`reneweddate` AS `reneweddate`,
    s.`itemtype` AS `itemtype`,
    s.`previousitemtype` AS `previousitemtype`,
    s.`mana_id` AS `mana_id`,
    s.`ccode` AS `ccode`,
    s.`published_on_template` AS `published_on_template`,
    fr.description AS `frequency_label`,
    NULL AS `biblio_periodicity`,
    br.branchname AS `library_name`,
    it.description AS `itemtype_label`,
    NULL AS `audience_from_itemtype`,
    np.label AS `numbering_pattern_label`,
    np.description AS `numbering_pattern_description`,
    fr.unit AS `frequency_unit`,
    fr.unitsperissue AS `frequency_unitsperissue`,
    fr.issuesperunit AS `frequency_issuesperunit`,
    NULL AS `marc326a_raw`,
    NULL AS `marc100a_raw`,
    sh.histstartdate AS `serial_history_start`,
    sh.histenddate AS `serial_history_end`,
    sh.opacnote AS `serial_history_public_note`,
    sh.librariannote AS `serial_history_staff_note`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND 1=1) AS `issues_total`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status=1) AS `issues_expected`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status=3) AS `issues_late`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status IN (4,41,42,43,44)) AS `issues_missing`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status=7) AS `issues_claimed_status`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status=2) AS `issues_received`,
    NULL AS `issue_claim_events_count`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.claimdate IS NOT NULL) AS `issues_with_claim_date`,
    (SELECT COUNT(*) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status IN (1,3,4,41,42,43,44) AND x.planneddate < DATE_SUB(CURDATE(), INTERVAL COALESCE(s.graceperiod,0) DAY)) AS `issues_claimable_now`,
    (SELECT MIN(x.planneddate) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status IN (1,3,4,41,42,43,44) AND x.planneddate < DATE_SUB(CURDATE(), INTERVAL COALESCE(s.graceperiod,0) DAY)) AS `oldest_claimable_date`,
    (SELECT MIN(x.planneddate) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status=1) AS `next_expected_date`,
    (SELECT MAX(x.publisheddate) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND x.status=2) AS `latest_received_date`,
    (SELECT MAX(x.claimdate) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND 1=1) AS `latest_claim_date`,
    (SELECT MAX(x.planneddate) FROM serial x WHERE x.subscriptionid=s.subscriptionid AND 1=1) AS `last_issue_planned_date`,
    NULL AS `days_since_oldest_claimable`,
    DATEDIFF(s.enddate,CURDATE()) AS `days_until_subscription_end`,
    (s.closed=0 AND s.enddate<CURDATE()) AS `expired_but_open`,
    (s.closed=0 AND s.enddate BETWEEN CURDATE() AND DATE_ADD(CURDATE(),INTERVAL 60 DAY)) AS `ending_within_60_days`
FROM subscription s
JOIN biblio b ON b.biblionumber=s.biblionumber
LEFT JOIN biblioitems bi ON bi.biblionumber=b.biblionumber
LEFT JOIN aqbooksellers v ON v.id=s.aqbooksellerid
LEFT JOIN branches br ON br.branchcode=s.branchcode
LEFT JOIN itemtypes it ON it.itemtype=s.itemtype
LEFT JOIN subscription_frequencies fr ON fr.id=s.periodicity
LEFT JOIN subscription_numberpatterns np ON np.id=s.numberpattern
LEFT JOIN subscriptionhistory sh ON sh.subscriptionid=s.subscriptionid
ORDER BY s.subscriptionid
